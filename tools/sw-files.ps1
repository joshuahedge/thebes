# Writes sw-files.js: the files the service worker caches, and a build stamp that changes whenever any of
# them does, so a deploy installs a fresh cache. Run it after adding or changing files and before a publish.
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$rel = { param($path) $path.Substring($root.Length + 1) -replace '\\', '/' }

# Version 9.1 (Track P, ruling 1685): index.html's preload block, written first (index.html is in the build stamp). Every module src/main.js
# imports, directly or not, through static import and export-from lines (a dynamic import() stays lazy), in the order the browser meets them
# (depth first from main.js), as <link rel="modulepreload">, so the browser asks for the whole tree at once instead of a level at a time.
$importLine = [regex]'(?s)(?:^|[;\n}])\s*(?:import|export)\s+(?:[^;''"`()]*?\s+from\s+)?[''"](\.{1,2}/[^''"]+\.js)[''"]'
$seen = [System.Collections.Generic.HashSet[string]]::new()
$order = [System.Collections.Generic.List[string]]::new()
function Add-Module([string]$file) {
  if (-not $seen.Add($file)) { return }
  $order.Add($file)
  $text = [IO.File]::ReadAllText((Join-Path $root $file))
  $dir = [IO.Path]::GetDirectoryName((Join-Path $root $file))
  foreach ($m in $importLine.Matches($text)) {
    $full = [IO.Path]::GetFullPath((Join-Path $dir $m.Groups[1].Value))
    if (Test-Path -LiteralPath $full) { Add-Module (& $rel $full) }
  }
}
Add-Module 'src/main.js'
$indexPath = Join-Path $root 'index.html'
$index = [IO.File]::ReadAllText($indexPath)
$open = '<!-- v91 preload -->'; $close = '<!-- end v91 preload -->'
$a = $index.IndexOf($open); $b = $index.IndexOf($close)
if ($a -ge 0 -and $b -gt $a) {
  $links = ($order | ForEach-Object { "<link rel=`"modulepreload`" href=`"./$_`">" }) -join "`n"
  $index = $index.Substring(0, $a + $open.Length) + "`n" + $links + "`n" + $index.Substring($b)
  [IO.File]::WriteAllText($indexPath, $index, [Text.UTF8Encoding]::new($false))
}
$files = @('index.html', 'manifest.webmanifest') +
  @(Get-ChildItem -Path (Join-Path $root 'css') -Filter *.css | ForEach-Object { 'css/' + $_.Name }) +   # Version 8.0: every stylesheet in css/, so a new one is cached without editing this line
  @(Get-ChildItem -Path (Join-Path $root 'src') -Recurse -Filter *.js | ForEach-Object { & $rel $_.FullName }) +
  @(Get-ChildItem -Path (Join-Path $root 'icons') -Filter *.png | ForEach-Object { 'icons/' + $_.Name }) +
  @(Get-ChildItem -Path (Join-Path $root 'assets/tutorial') -File -ErrorAction SilentlyContinue | ForEach-Object { 'assets/tutorial/' + $_.Name })   # Stage 4: the picture cards (tools/tutorial.ps1)
$files = @($files | Sort-Object -Unique)
$version = (Select-String -Path (Join-Path $root 'src/data/ui.js') -Pattern "APP_VERSION = '([^']+)'").Matches[0].Groups[1].Value
$all = New-Object System.IO.MemoryStream
foreach ($f in $files) { $bytes = [IO.File]::ReadAllBytes((Join-Path $root $f)); $all.Write($bytes, 0, $bytes.Length) }
$sha = [System.Security.Cryptography.SHA1]::Create()
$build = ([BitConverter]::ToString($sha.ComputeHash($all.ToArray())) -replace '-', '').Substring(0, 12).ToLower()
$list = ($files | ForEach-Object { "  './$_'," }) -join "`n"
$text = "// Generated by tools/sw-files.ps1. Do not edit: run the tool after adding or changing files.`n" +
  "self.THEBES_VERSION = '$version';`nself.THEBES_BUILD = '$build';`nself.THEBES_FILES = [`n  './',`n$list`n];`n"
[IO.File]::WriteAllText((Join-Path $root 'sw-files.js'), $text, [Text.UTF8Encoding]::new($false))
Write-Output "Wrote sw-files.js: $($files.Count + 1) entries, version $version, build $build; index.html preloads $($order.Count) modules"
